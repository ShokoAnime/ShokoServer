using System.Reflection;
using System.Text;

namespace Shoko.BuildTools;

/// <summary>
///   Generates C# assembly metadata files for plugin builds and reads the
///   metadata back from compiled assemblies.
/// </summary>
internal static class AssemblyInfoGenerator
{
    /// <summary>
    ///   Assembly metadata key for the serialized dependency string.
    /// </summary>
    private const string DependenciesKey = "PackageDependencies";

    /// <summary>
    ///   Write a generated .cs file with assembly-level metadata attributes.
    /// </summary>
    public static void WriteAssemblyInfo(
        string path,
        string runtimeIdentifier,
        string releaseDate,
        string releaseTag,
        string sourceRevision,
        IReadOnlyList<DependencyInfo> dependencies,
        IReadOnlyList<string>? tags,
        Guid? pluginId = null,
        string? pluginName = null,
        string? pluginDescription = null)
    {
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated>");
        sb.AppendLine("// This file is generated by Shoko.BuildTools. Do not edit manually.");
        sb.AppendLine("// </auto-generated>");
        sb.AppendLine();
        sb.AppendLine("using System.Reflection;");
        sb.AppendLine();

        if (!string.IsNullOrEmpty(runtimeIdentifier))
            sb.AppendLine($"[assembly: AssemblyMetadata(\"RuntimeIdentifier\", \"{EscapeAttrValue(runtimeIdentifier)}\")]");

        if (!string.IsNullOrEmpty(releaseDate))
            sb.AppendLine($"[assembly: AssemblyMetadata(\"ReleaseDate\", \"{EscapeAttrValue(releaseDate)}\")]");

        if (!string.IsNullOrEmpty(releaseTag))
            sb.AppendLine($"[assembly: AssemblyMetadata(\"ReleaseTag\", \"{EscapeAttrValue(releaseTag)}\")]");

        if (!string.IsNullOrEmpty(sourceRevision))
            sb.AppendLine($"[assembly: AssemblyMetadata(\"SourceRevision\", \"{EscapeAttrValue(sourceRevision)}\")]");

        // Inject tags from manifest as a single comma-separated PackageTags
        // attribute, matching the format the server reads at runtime.
        if (tags is { Count: > 0 })
        {
            var filtered = tags.Where(t => !string.IsNullOrEmpty(t)).ToList();
            if (filtered.Count > 0)
                sb.AppendLine($"[assembly: AssemblyMetadata(\"PackageTags\", \"{EscapeAttrValue(string.Join(",", filtered))}\")]");
        }

        // Inject plugin identity from manifest (so the server can read it
        // without instantiating the plugin type)
        if (pluginId.HasValue)
            sb.AppendLine($"[assembly: AssemblyMetadata(\"PackageID\", \"{pluginId.Value:D}\")]");

        if (!string.IsNullOrEmpty(pluginName))
            sb.AppendLine($"[assembly: AssemblyMetadata(\"PackageName\", \"{EscapeAttrValue(pluginName)}\")]");

        if (!string.IsNullOrEmpty(pluginDescription))
            sb.AppendLine($"[assembly: AssemblyMetadata(\"PackageOverview\", \"{EscapeAttrValue(pluginDescription)}\")]");

        // Inject dependencies as a single serialized string:
        //   guid:versionRange[:true][,next]*
        if (dependencies.Count > 0)
        {
            var serialized = string.Join(",",
                dependencies.Select(d =>
                {
                    var s = $"{d.PluginID:D}:{d.VersionRange}";
                    if (d.IsOptional) s += ":true";
                    return s;
                }));
            sb.AppendLine($"[assembly: AssemblyMetadata(\"{DependenciesKey}\", \"{EscapeAttrValue(serialized)}\")]");
        }

        File.WriteAllText(path, sb.ToString());
    }

    /// <summary>
    ///   Read embedded metadata from a compiled plugin DLL.
    /// </summary>
    public static AssemblyMetadata ReadAssemblyMetadata(string dllPath)
    {
        var assembly = Assembly.LoadFrom(dllPath);
        var metadata = assembly.GetCustomAttributes<AssemblyMetadataAttribute>()
            .ToLookup(a => a.Key, a => a.Value, StringComparer.OrdinalIgnoreCase);

        var version = assembly.GetName().Version;
        var abstractionVersion = assembly.GetReferencedAssemblies()
            .FirstOrDefault(r => r.Name == "Shoko.Abstractions")
            ?.Version;

        var dependencies = new List<DependencyInfo>();

        // Try the serialized format first (single attribute with comma-separated deps)
        if (metadata[DependenciesKey].FirstOrDefault() is { } serialized && !string.IsNullOrEmpty(serialized))
        {
            foreach (var segment in serialized.Split(','))
            {
                var parts = segment.Split(':');
                if (parts.Length >= 2 && Guid.TryParse(parts[0], out var pluginId))
                {
                    dependencies.Add(new DependencyInfo
                    {
                        PluginID = pluginId,
                        VersionRange = parts[1],
                        IsOptional = parts.Length > 2 && (parts[2] == "true" || parts[2] == "True"),
                    });
                }
            }
        }

        return new AssemblyMetadata
        {
            Version = version is not null ? new Version(version.Major, version.Minor, version.Build) : new Version(0, 0, 0),
            AbstractionVersion = abstractionVersion is not null ? new Version(abstractionVersion.Major, abstractionVersion.Minor, abstractionVersion.Build) : new Version(0, 0, 0),
            Dependencies = dependencies,
            Tags = metadata["Tag"].Where(t => t is not null).Cast<string>().ToList(),
        };
    }

    private static string EscapeAttrValue(string value)
        => value.Replace("\\", "\\\\").Replace("\"", "\\\"");
}

/// <summary>
///   Metadata read from a compiled plugin assembly.
/// </summary>
internal sealed class AssemblyMetadata
{
    public Version Version { get; init; } = new(0, 0, 0);
    public Version AbstractionVersion { get; init; } = new(0, 0, 0);
    public IReadOnlyList<DependencyInfo> Dependencies { get; init; } = [];
    public IReadOnlyList<string> Tags { get; init; } = [];
}

/// <summary>
///   A dependency declaration for embedding into manifest and assembly.
/// </summary>
internal sealed class DependencyInfo
{
    public Guid PluginID { get; init; }
    public string VersionRange { get; init; } = ">=0.0.0";
    public bool IsOptional { get; init; }
}
