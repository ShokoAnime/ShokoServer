using System.Text;
using Microsoft.Build.Framework;

namespace Shoko.BuildTools.Tasks;

/// <summary>
///   Stamps <c>PackageIsMeta</c>: whether the plugin is a metadata
///   plugin, one whose only code is its generated plugin class, so it only
///   brings in its dependencies. Worked out from the project's compile items,
///   never set by hand.
/// </summary>
public class DetectMetaPlugin : Microsoft.Build.Utilities.Task
{
    /// <summary>
    ///   The assembly metadata key the result is stamped under.
    /// </summary>
    public const string MetadataKey = "PackageIsMeta";

    [Required]
    public string ProjectDir { get; set; } = string.Empty;

    [Required]
    public string OutputPath { get; set; } = string.Empty;

    /// <summary>
    ///   Whether the project sets <c>PluginGenerateClass</c>.
    /// </summary>
    public bool GenerateClass { get; set; }

    /// <summary>
    ///   <c>@(Compile)</c>, as the compiler is about to get it.
    /// </summary>
    public ITaskItem[]? CompileItems { get; set; }

    /// <summary>
    ///   The folders generated sources live in: <c>$(BaseIntermediateOutputPath)</c>
    ///   and <c>$(IntermediateOutputPath)</c>.
    /// </summary>
    public string[]? GeneratedFolders { get; set; }

    /// <summary>
    ///   Generated sources outside those folders, such as the assembly info
    ///   file <c>shoko-build</c> writes.
    /// </summary>
    public string[]? GeneratedFiles { get; set; }

    public override bool Execute()
    {
        var isMeta = IsMetaPlugin(
            GenerateClass,
            (CompileItems ?? []).Select(item => item.ItemSpec),
            GeneratedFolders ?? [],
            GeneratedFiles ?? [],
            ProjectDir
        );

        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated>");
        sb.AppendLine("// Generated by Shoko.BuildTools.Tasks.DetectMetaPlugin");
        sb.AppendLine("// </auto-generated>");
        sb.AppendLine("using System.Reflection;");
        sb.AppendLine();
        sb.AppendLine($"[assembly: AssemblyMetadata(\"{MetadataKey}\", \"{(isMeta ? "true" : "false")}\")]");

        var written = GeneratedFile.Write(OutputPath, sb.ToString());
        Log.LogMessage(MessageImportance.Normal, written ? "Generated: {0}" : "Unchanged: {0}", OutputPath);
        return true;
    }

    /// <summary>
    ///   Whether a project is a meta plugin: it generates its plugin
    ///   class and compiles no source of its own.
    /// </summary>
    /// <param name="generateClass">Whether the project sets <c>PluginGenerateClass</c>.</param>
    /// <param name="compileItems">The paths of every compile item, absolute or relative to <paramref name="projectDir" />.</param>
    /// <param name="generatedFolders">The folders whose files are generated, not the project's own.</param>
    /// <param name="generatedFiles">Generated files outside those folders.</param>
    /// <param name="projectDir">The project's folder, which relative paths are resolved against.</param>
    /// <returns><c>true</c> when every compile item is generated and the plugin class is too.</returns>
    internal static bool IsMetaPlugin(
        bool generateClass,
        IEnumerable<string> compileItems,
        IEnumerable<string> generatedFolders,
        IEnumerable<string> generatedFiles,
        string projectDir
    )
    {
        if (!generateClass)
            return false;

        var comparison = OperatingSystem.IsWindows() || OperatingSystem.IsMacOS() ? StringComparison.OrdinalIgnoreCase : StringComparison.Ordinal;
        var folders = generatedFolders
            .Where(folder => !string.IsNullOrWhiteSpace(folder))
            .Select(folder => Path.TrimEndingDirectorySeparator(Resolve(folder)) + Path.DirectorySeparatorChar)
            .ToList();
        var files = generatedFiles
            .Where(file => !string.IsNullOrWhiteSpace(file))
            .Select(Resolve)
            .ToList();

        return compileItems
            .Where(item => !string.IsNullOrWhiteSpace(item))
            .Select(Resolve)
            .All(item => files.Any(file => string.Equals(file, item, comparison)) || folders.Any(folder => item.StartsWith(folder, comparison)));

        // MSBuild writes its paths with backslashes on every system.
        string Resolve(string path)
            => Path.GetFullPath(OperatingSystem.IsWindows() ? path.Trim() : path.Trim().Replace('\\', '/'), projectDir);
    }
}
