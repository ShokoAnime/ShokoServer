using System.Text;
using System.Text.Json;
using Microsoft.Build.Framework;
using Microsoft.Build.Utilities;

namespace Shoko.BuildTools.Tasks;

/// <summary>
///   MSBuild task that reads a plugin's manifest.json and writes a .cs file
///   with assembly metadata attributes for PackageID, PackageName,
///   PackageOverview, tags, and dependencies.
/// </summary>
public class ReadPluginManifest : Microsoft.Build.Utilities.Task
{
    /// <summary>
    ///   The project directory to search for manifest.json.
    /// </summary>
    [Required]
    public string ProjectDir { get; set; } = string.Empty;

    /// <summary>
    ///   The intermediate output path for the generated .cs file.
    /// </summary>
    [Required]
    public string OutputPath { get; set; } = string.Empty;

    public override bool Execute()
    {
        try
        {
            var manifestPath = FindManifest(ProjectDir);
            if (manifestPath is null)
            {
                Log.LogMessage(MessageImportance.Low, "No manifest.json found near {0}", ProjectDir);
                return true;
            }

            Log.LogMessage(MessageImportance.Normal, "Reading plugin manifest: {0}", manifestPath);

            var json = File.ReadAllText(manifestPath);
            using var doc = JsonDocument.Parse(json);
            var root = doc.RootElement;

            var sb = new StringBuilder();
            sb.AppendLine("// <auto-generated>");
            sb.AppendLine("// Generated by Shoko.BuildTools.Tasks.ReadPluginManifest");
            sb.AppendLine("// </auto-generated>");
            sb.AppendLine("using System.Reflection;");
            sb.AppendLine();

            // PackageID
            if (root.TryGetProperty("id", out var idEl) && idEl.ValueKind == JsonValueKind.String)
                sb.AppendLine($"[assembly: AssemblyMetadata(\"PackageID\", \"{Escape(idEl.GetString()!)}\")]");

            // PackageName
            if (root.TryGetProperty("name", out var nameEl) && nameEl.ValueKind == JsonValueKind.String)
                sb.AppendLine($"[assembly: AssemblyMetadata(\"PackageName\", \"{Escape(nameEl.GetString()!)}\")]");

            // PackageOverview
            if (root.TryGetProperty("overview", out var descEl) && descEl.ValueKind == JsonValueKind.String)
                sb.AppendLine($"[assembly: AssemblyMetadata(\"PackageOverview\", \"{Escape(descEl.GetString()!)}\")]");

            // Tags as comma-separated PackageTags
            if (root.TryGetProperty("tags", out var tagsEl) && tagsEl.ValueKind == JsonValueKind.Array)
            {
                var t = string.Join(",", tagsEl.EnumerateArray()
                    .Select(t => t.GetString()).Where(t => t is not null));
                if (t.Length > 0)
                    sb.AppendLine($"[assembly: AssemblyMetadata(\"PackageTags\", \"{Escape(t)}\")]");
            }

            // Dependencies as serialized string
            if (root.TryGetProperty("dependencies", out var depsEl) && depsEl.ValueKind == JsonValueKind.Array)
            {
                var deps = string.Join(",",
                    depsEl.EnumerateArray().Select(d =>
                    {
                        var did = d.GetProperty("id").GetString()!;
                        var dver = d.GetProperty("version").GetString()!;
                        var opt = d.TryGetProperty("optional", out var o) && o.GetBoolean();
                        return opt ? $"{did}:{dver}:true" : $"{did}:{dver}";
                    }));
                if (deps.Length > 0)
                    sb.AppendLine($"[assembly: AssemblyMetadata(\"PackageDependencies\", \"{Escape(deps)}\")]");
            }

            // Add the RuntimeIdentifier for portable libs
            sb.AppendLine($"[assembly: AssemblyMetadata(\"RuntimeIdentifier\", \"any\")]");

            File.WriteAllText(OutputPath, sb.ToString());
            Log.LogMessage(MessageImportance.Normal, "Generated: {0}", OutputPath);
            return true;
        }
        catch (Exception ex)
        {
            Log.LogError("Failed to read plugin manifest: {0}", ex.Message);
            return false;
        }
    }

    private static string Escape(string value)
        => value.Replace("\\", "\\\\").Replace("\"", "\\\"");

    private static string? FindManifest(string projectDir)
    {
        var dir = projectDir.TrimEnd(Path.DirectorySeparatorChar, Path.AltDirectorySeparatorChar);

        var local = Path.Combine(dir, "manifest.json");
        if (File.Exists(local))
            return local;

        var parent = Path.GetDirectoryName(dir);
        if (parent is not null)
        {
            var parentManifest = Path.Combine(parent, "manifest.json");
            if (File.Exists(parentManifest))
                return parentManifest;
        }

        return null;
    }
}
