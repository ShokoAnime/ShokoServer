using System.Text;
using Microsoft.Build.Framework;

namespace Shoko.BuildTools.Tasks;

/// <summary>
///   Writes the plugin's <c>IPlugin</c> class for a project that sets
///   <c>PluginGenerateClass</c>: a partial class reading its ID, name and
///   overview from what the build stamps into the assembly, so the project's
///   <c>Plugin*</c> properties are the only place they are written. The
///   project adds behaviour, or <c>IPlugin&lt;TConfiguration&gt;</c>, in a
///   partial class of its own.
/// </summary>
public class GeneratePluginClass : Microsoft.Build.Utilities.Task
{
    /// <summary>
    ///   The file to write.
    /// </summary>
    [Required]
    public string OutputPath { get; set; } = string.Empty;

    /// <summary>
    ///   The class's namespace, <c>$(RootNamespace)</c> by default.
    /// </summary>
    [Required]
    public string Namespace { get; set; } = string.Empty;

    /// <summary>
    ///   The class's name, <c>$(PluginClassName)</c>, <c>Plugin</c> by
    ///   default.
    /// </summary>
    [Required]
    public string ClassName { get; set; } = string.Empty;

    public override bool Execute()
    {
        if (!IsIdentifier(ClassName))
        {
            Log.LogError("PluginClassName '{0}' is not a valid C# class name.", ClassName);
            return false;
        }

        if (!Namespace.Split('.').All(IsIdentifier))
        {
            Log.LogError("The namespace '{0}' for the generated plugin class is not a valid C# namespace; set RootNamespace.", Namespace);
            return false;
        }

        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated>");
        sb.AppendLine("// Generated by Shoko.BuildTools.Tasks.GeneratePluginClass, from the project's Plugin* properties.");
        sb.AppendLine("// </auto-generated>");
        sb.AppendLine("#nullable enable");
        sb.AppendLine();
        sb.AppendLine($"namespace {Namespace}");
        sb.AppendLine("{");
        sb.AppendLine("    /// <summary>");
        sb.AppendLine("    ///   The plugin, with the identity the build stamped into the assembly.");
        sb.AppendLine("    /// </summary>");
        sb.AppendLine("    [global::System.CodeDom.Compiler.GeneratedCode(\"Shoko.BuildTools.Tasks.GeneratePluginClass\", null)]");
        sb.AppendLine($"    public partial class {ClassName} : global::Shoko.Abstractions.Plugin.IPlugin");
        sb.AppendLine("    {");
        sb.AppendLine($"        private static readonly global::System.Guid _id = global::System.Guid.Parse(GetMetadata(\"PackageID\") ?? throw new global::System.InvalidOperationException(\"The plugin has no PackageID; set PluginID in the project.\"));");
        sb.AppendLine();
        sb.AppendLine($"        private static readonly string _name = GetMetadata(\"PackageName\") ?? typeof({ClassName}).Assembly.GetName().Name ?? \"{ClassName}\";");
        sb.AppendLine();
        sb.AppendLine("        private static readonly string? _description = GetMetadata(\"PackageOverview\");");
        sb.AppendLine();
        sb.AppendLine("        /// <inheritdoc/>");
        sb.AppendLine("        public global::System.Guid ID => _id;");
        sb.AppendLine();
        sb.AppendLine("        /// <inheritdoc/>");
        sb.AppendLine("        public string Name => _name;");
        sb.AppendLine();
        sb.AppendLine("        /// <inheritdoc/>");
        sb.AppendLine("        public string? Description => _description;");
        sb.AppendLine();
        sb.AppendLine("        private static string? GetMetadata(string key)");
        sb.AppendLine("        {");
        sb.AppendLine($"            foreach (var attribute in global::System.Reflection.CustomAttributeExtensions.GetCustomAttributes<global::System.Reflection.AssemblyMetadataAttribute>(typeof({ClassName}).Assembly))");
        sb.AppendLine("            {");
        sb.AppendLine("                if (attribute.Key == key)");
        sb.AppendLine("                    return attribute.Value;");
        sb.AppendLine("            }");
        sb.AppendLine();
        sb.AppendLine("            return null;");
        sb.AppendLine("        }");
        sb.AppendLine("    }");
        sb.AppendLine("}");

        Directory.CreateDirectory(Path.GetDirectoryName(Path.GetFullPath(OutputPath))!);
        var written = GeneratedFile.Write(OutputPath, sb.ToString());
        Log.LogMessage(MessageImportance.Normal, written ? "Generated: {0}" : "Unchanged: {0}", OutputPath);
        return true;
    }

    private static bool IsIdentifier(string value)
        => value.Length > 0 &&
            (char.IsLetter(value[0]) || value[0] == '_') &&
            value.All(c => char.IsLetterOrDigit(c) || c == '_');
}
